"""
Writes src/pdf/qr.ts: the QR codes printed on page 2 of the creative CV, which
open the interactive resume in the reader's language. Stored as vector paths
(one rectangle per run of dark modules), so the PDF prints them crisp at any
size and the browser bundle needs no QR library.

Requires: pip install segno
Run after changing the site URL:  python scripts/pdf-qr.py
"""
import os
import segno

SITE = "https://resume-khristian-garcia.pages.dev/resume"
OUT = os.path.join("src", "pdf", "qr.ts")


def path_for(url: str) -> tuple[int, str]:
    qr = segno.make(url, error="m", micro=False)
    rows = list(qr.matrix_iter(scale=1, border=0))
    parts = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x]:
                start = x
                while x < len(row) and row[x]:
                    x += 1
                parts.append(f"M{start} {y}h{x - start}v1h-{x - start}z")
            else:
                x += 1
    return len(rows), "".join(parts)


entries = []
for lang in ("en", "es"):
    url = f"{SITE}?lang={lang}"
    size, d = path_for(url)
    entries.append(f"  {lang}: {{ url: '{url}', size: {size}, d: '{d}' }},")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/pdf-qr.py: do not edit by hand.\n")
    f.write("/** QR codes to the interactive resume, as SVG paths in module units (no quiet zone) */\n")
    f.write("export const RESUME_QR: Record<'en' | 'es', { url: string; size: number; d: string }> = {\n")
    f.write("\n".join(entries) + "\n};\n")
print("ok", OUT)
